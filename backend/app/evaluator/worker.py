def codex_environment(settings: EvaluatorRuntimeSettings) -> dict[str, str]:
    environment = without_web_credentials(os.environ)
    environment["CODEX_HOME"] = str(settings.codex_home)
    environment["ARENA_INTERNAL_MCP_API_KEY"] = settings.internal_token
    environment["MASSIVE_API_KEY"] = settings.massive_api_key
    environment.pop("OPENAI_API_KEY", None)
    environment.pop("CODEX_API_KEY", None)
    environment.pop("META_API_KEY", None)
    return environment


async def internal_request(
    settings: EvaluatorRuntimeSettings,
    method: str,
    path: str,
    payload: dict | None = None,
) -> dict:
    if not settings.internal_token:
        raise RuntimeError("ARENA_INTERNAL_MCP_API_KEY is unavailable")
    timeout = httpx.Timeout(30, read=60)
    async with httpx.AsyncClient(
        base_url=settings.internal_api_url,
        headers={"Authorization": f"Bearer {settings.internal_token}"},
        timeout=timeout,
    ) as client:
        response = await client.request(method, path, json=payload)
        response.raise_for_status()
        result = response.json()
        if not isinstance(result, dict):
            raise RuntimeError("Internal evaluator API returned a non-object response")
        return result


async def codex_version() -> str:
    executable = shutil.which("codex")
    if executable is None:
        raise RuntimeError("codex executable is not installed")
    process = await asyncio.create_subprocess_exec(
        executable,
        "--version",
        stdin=asyncio.subprocess.DEVNULL,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
        env=without_web_credentials(os.environ),
        start_new_session=True,
    )
    try:
        stdout, stderr = await asyncio.wait_for(process.communicate(), timeout=30)
    except TimeoutError:
        raise RuntimeError("Codex version check timed out") from None
    finally:
        await _stop_process(process)
    if process.returncode != 0:
        raise RuntimeError((stderr or stdout).decode(errors="replace").strip())
    return stdout.decode().strip()


