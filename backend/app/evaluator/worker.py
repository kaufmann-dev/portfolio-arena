async def _wait_for_cancellation(
    settings: EvaluatorRuntimeSettings,
    run: ClaimedRun,
) -> str:
    while True:
        await asyncio.sleep(2)
        try:
            control = await internal_request(
                settings, "GET", f"/runs/{run.id}/control?attempt_count={run.attempt_count}"
            )
        except httpx.HTTPStatusError as exc:
            if exc.response.status_code == 404:
                return "Portfolio or evaluation run was deleted."
            if exc.response.status_code == 409:
                return "Evaluation attempt was superseded."
            logger.exception("evaluation_control_poll_failed run_id=%s", run.id)
            continue
        except Exception:
            logger.exception("evaluation_control_poll_failed run_id=%s", run.id)
            continue
        if control.get("status") in {"cancel_requested", "cancelled"}:
            return "Cancelled by an administrator."


async def _stop_process(process: asyncio.subprocess.Process) -> None:
    # Each evaluation owns a process group, including its MCP children.
    # Clean the group even if the harness parent has already exited.
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        await asyncio.wait_for(process.wait(), timeout=5)
    except TimeoutError:
        pass
    finally:
        # The parent can exit while an MCP child ignores SIGTERM or holds the
        # output pipes open. Always finish cleanup of the entire group.
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        await process.wait()


async def _communicate_run(
    settings: EvaluatorRuntimeSettings,
    run: ClaimedRun,
    process: asyncio.subprocess.Process,
    prompt: bytes | None,
) -> tuple[bytes, bytes]:
    communicate_task = asyncio.create_task(process.communicate(prompt))
    cancellation_task = asyncio.create_task(_wait_for_cancellation(settings, run))
    try:
        done, _ = await asyncio.wait(
            {communicate_task, cancellation_task},
            timeout=run.timeout_seconds,
            return_when=asyncio.FIRST_COMPLETED,
        )
        if cancellation_task in done:
            raise RunCancelled(cancellation_task.result())
        if communicate_task not in done:
            raise RuntimeError(f"{run.harness} attempt exceeded {run.timeout_seconds} seconds")
        return communicate_task.result()
    finally:
        cancellation_task.cancel()
        await _stop_process(process)
        await asyncio.gather(communicate_task, cancellation_task, return_exceptions=True)


async def run_codex(
    settings: EvaluatorRuntimeSettings,
    run: ClaimedRun,
) -> Proposal:
    schema_path = Path(__file__).with_name("proposal.schema.json")
    with tempfile.TemporaryDirectory(prefix="arena-evaluation-") as temp_dir:
        output_path = Path(temp_dir) / "proposal.json"
        command = [
            "codex",
            "exec",
            "--strict-config",
            "--ephemeral",
            "--skip-git-repo-check",
            "--ignore-rules",
            "--sandbox",
            "read-only",
            "--model",
            run.execution_model_id,
        ]
        if run.reasoning_effort is not None:
            command.extend(["--config", f'model_reasoning_effort="{run.reasoning_effort}"'])
        command.extend(
            [
                "--cd",
                temp_dir,
                "--output-schema",
                str(schema_path),
                "--output-last-message",
                str(output_path),
                "--color",
                "never",
                "-",
            ]
        )
        process = await asyncio.create_subprocess_exec(
            *command,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            env=codex_environment(settings),
            start_new_session=True,
        )
        stdout, stderr = await _communicate_run(settings, run, process, evaluator_prompt(run).encode())
        if process.returncode != 0:
            detail = (stderr or stdout).decode(errors="replace").strip()
            raise RuntimeError(detail[-4000:] or f"Codex exited with {process.returncode}")
        if not output_path.exists():
            raise RuntimeError("Codex completed without writing a proposal")
        return Proposal.model_validate_json(output_path.read_text())


async def run_muse(settings: EvaluatorRuntimeSettings, run: ClaimedRun) -> Proposal:
    schema = Path(__file__).with_name("proposal.schema.json").read_text()
    prompt = (
        f"{evaluator_prompt(run)}\n\n"
        "Return the final result as one JSON object, without commentary or Markdown fences. "
        "The worker validates this JSON against the following schema before submitting it.\n"
        f"{schema}"
    )
    with tempfile.TemporaryDirectory(prefix="arena-muse-evaluation-") as temp_dir:
        workspace = Path(temp_dir)
        prompt_path = workspace / "prompt.txt"
        prompt_path.write_text(prompt)
        process = await asyncio.create_subprocess_exec(
            *muse_command(run.execution_model_id, run.reasoning_effort, workspace, prompt_path),
            stdin=asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            cwd=workspace,
            env=muse_environment(settings),
            start_new_session=True,
        )
        stdout, stderr = await _communicate_run(settings, run, process, None)
        if process.returncode != 0:
            # Prefer the structured terminal reason when Muse produced one.
            try:
                muse_result(stdout)
            except ValueError as exc:
                detail = f"{exc}\n{stderr.decode(errors='replace')}".strip()
                raise RuntimeError(detail[-4000:]) from exc
            detail = stderr.decode(errors="replace")[-4000:] or f"Muse exited with {process.returncode}"
            raise RuntimeError(detail)
        return _proposal_from_prompt_guided_json(muse_result(stdout))


async def run_opencode(settings: EvaluatorRuntimeSettings, run: ClaimedRun) -> Proposal:
    schema = Path(__file__).with_name("proposal.schema.json").read_text()
    prompt = (
        f"{evaluator_prompt(run)}\n\n"
        "Return the final result as one JSON object, without commentary or Markdown fences. "
        "The worker validates this JSON against the following schema before submitting it.\n"
        f"{schema}"
    )
    try:
        # Preflight and inference share one attempt deadline. Both subprocesses
        # also participate in administrator cancellation and process-group cleanup.
        async with asyncio.timeout(run.timeout_seconds):
            models = await opencode_available_models(settings, run)
            validate_opencode_model(models, run.execution_model_id, run.reasoning_effort)
            with tempfile.TemporaryDirectory(prefix="arena-opencode-evaluation-") as directory:
                workspace = Path(directory)
                process = await asyncio.create_subprocess_exec(
                    *opencode_command(run.execution_model_id, run.reasoning_effort, workspace),
                    stdin=asyncio.subprocess.PIPE,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                    cwd=workspace,
                    env=opencode_environment(settings),
                    start_new_session=True,
                )
                stdout, stderr = await _communicate_run(settings, run, process, prompt.encode())
                if process.returncode != 0:
                    try:
                        opencode_result(stdout)
                    except ValueError as exc:
                        detail = f"{exc}\n{stderr.decode(errors='replace')}".strip()
                        raise RuntimeError(detail[-4000:]) from exc
                    raise RuntimeError(
                        stderr.decode(errors="replace")[-4000:]
                        or f"OpenCode exited with {process.returncode}"
                    )
                return _proposal_from_prompt_guided_json(opencode_result(stdout))
    except TimeoutError:
        raise RuntimeError(f"opencode attempt exceeded {run.timeout_seconds} seconds") from None


async def run_agy(settings: EvaluatorRuntimeSettings, run: ClaimedRun) -> Proposal:
    try:
        async with asyncio.timeout(run.timeout_seconds):
            models = await agy_available_models(settings, run=run)
            if not models:
                raise ValueError("Antigravity models are unavailable; check agy models")
            # The catalog lists effort-specific IDs, while the CLI also accepts
            # base IDs with --effort. Let native execution validate the selection.
            with tempfile.TemporaryDirectory(prefix="arena-agy-") as directory:
                command = agy_command(
                    settings,
                    "--input-format",
                    "stream-json",
                    "--model",
                    run.execution_model_id,
                    "--output-format",
                    "stream-json",
                    "--json-schema",
                    json.dumps(agy_proposal_schema()),
                    "--print-timeout",
                    f"{run.timeout_seconds}s",
                    "--disable-slash-commands",
                )
                if run.reasoning_effort is not None:
                    command.extend(["--effort", run.reasoning_effort])
                process = await asyncio.create_subprocess_exec(
                    *command,
                    stdin=asyncio.subprocess.PIPE,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                    cwd=directory,
                    env=agy_environment(settings),
                    start_new_session=True,
                )
                message = {"event": "user", "message": {"content": evaluator_prompt(run)}}
                stdin = (json.dumps(message) + "\n").encode()
                stdout, stderr = await _communicate_run(settings, run, process, stdin)
                if process.returncode != 0:
                    raise RuntimeError(
                        stderr.decode(errors="replace")[-4000:] or "Antigravity execution failed"
                    )
                return Proposal.model_validate(agy_result(stdout, stderr))
    except TimeoutError:
        raise RuntimeError(f"agy attempt exceeded {run.timeout_seconds} seconds") from None


async def evaluate_run(
    settings: EvaluatorRuntimeSettings,
    run: ClaimedRun,
) -> None:
    proposal = None
    try:
        runners = {"codex": run_codex, "muse": run_muse, "opencode": run_opencode, "agy": run_agy}
        proposal = await runners[run.harness](settings, run)
        if proposal.status == "blocked":
            raise EvaluationBlocked(f"{proposal.blocked_reason}: {proposal.error}")
        await internal_request(
            settings,
            "POST",
            f"/runs/{run.id}/submit",
            {
                "attempt_count": run.attempt_count,
                "positions": [position.model_dump() for position in proposal.positions],
                "note": proposal.note,
                "report": proposal.report,
            },
        )
        logger.info("evaluation_succeeded portfolio=%s run_id=%s", run.portfolio.slug, run.id)
    except RunCancelled as exc:
        logger.info("evaluation_cancelled portfolio=%s run_id=%s", run.portfolio.slug, run.id)
        try:
            await internal_request(
                settings,
                "POST",
                f"/runs/{run.id}/fail",
                {"attempt_count": run.attempt_count, "error": str(exc), "cancelled": True},
            )
        except httpx.HTTPStatusError as failure:
            if failure.response.status_code not in {404, 409}:
                raise
    except Exception as exc:
        message = f"{type(exc).__name__}: {exc}"
        logger.error(
            "evaluation_failed portfolio=%s run_id=%s error=%s",
            run.portfolio.slug,
            run.id,
            message,
        )
        try:
            await internal_request(
                settings,
                "POST",
                f"/runs/{run.id}/fail",
                {
                    "attempt_count": run.attempt_count,
                    "error": message[-4000:],
                    "cancelled": False,
                    "report": proposal.report if proposal else None,
                },
            )
        except Exception:
            logger.exception("evaluation_failure_record_failed run_id=%s", run.id)


async def scheduler(
    settings: EvaluatorRuntimeSettings,
    instance_id: str,
    state: WorkerState,
    harness: Literal["codex", "muse", "opencode", "agy"],
) -> None:
    active_tasks: set[asyncio.Task[None]] = set()
    catalog_verified = False
    try:
        while True:
            try:
                config_writers = {
                    "codex": write_codex_config,
                    "muse": write_muse_config,
                    "opencode": prepare_opencode,
                    "agy": write_agy_config,
                }
                config_writers[harness](settings)
                if not settings.massive_api_key:
                    state.status = "configuration_error"
                    state.authenticated = False
                    state.last_error = "MASSIVE_API_KEY is required."
                else:
                    if harness == "muse":
                        state.harness_version = await muse_version(settings)
                        state.authenticated = bool(muse_credential(settings))
                    elif harness == "codex":
                        state.harness_version = await codex_version()
                        state.authenticated = await codex_is_authenticated(settings)
                    elif harness == "opencode":
                        state.harness_version = await opencode_version(settings)
                        state.authenticated = any(
                            model.get("capabilities", {}).get("toolcall") is True
                            for model in (await opencode_available_models(settings)).values()
                        )
                    elif harness == "agy":
                        state.harness_version = await agy_version(settings)
                        state.authenticated = bool(await agy_available_models(settings))
                    if not state.authenticated:
                        state.status = "authentication_required"
                        login_hints = {
                            "agy": (
                                f"Run `agy --gemini_dir={shlex.quote(str(settings.agy_home))}` "
                                "in the application terminal to sign in to Antigravity."
                            ),
                            "codex": f"Run `CODEX_HOME={shlex.quote(str(settings.codex_home))} "
                            "codex login --device-auth` in the application terminal.",
                            "muse": f"Run `XDG_CONFIG_HOME={shlex.quote(str(settings.muse_config_home))} "
                            "muse login` in the application terminal or configure META_API_KEY.",
                            "opencode": (
                                f"Run `XDG_CONFIG_HOME={shlex.quote(str(settings.opencode_home / 'config'))} "
                                f"XDG_DATA_HOME={shlex.quote(str(settings.opencode_home / 'data'))} "
                                "opencode auth login` in the application terminal, or configure a provider "
                                "with a tool-capable model."
                            ),
                        }
                        state.last_error = login_hints[harness]
                    else:
                        if harness == "muse" and not catalog_verified:
                            await fetch_muse_catalog(settings)
                            catalog_verified = True
                        response = ClaimResponse.model_validate(
                            await internal_request(
                                settings,
                                "POST",
                                "/claim",
                                {
                                    "worker_id": instance_id,
                                    "harness": harness,
                                    "harness_version": state.harness_version,
                                    "limit": 20,
                                },
                            )
                        )
                        state.poll_seconds = response.settings.poll_seconds
                        active_tasks.update(
                            asyncio.create_task(evaluate_run(settings, run)) for run in response.runs
                        )
                        state.active_run_count = len(active_tasks)
                        state.last_error = None
                        if not response.settings.enabled:
                            state.status = "paused"
                        elif active_tasks:
                            state.status = "running"
                        else:
                            state.status = "idle"
            except asyncio.CancelledError:
                raise
            except AgyAuthenticationRequired as exc:
                state.status = "authentication_required"
                state.authenticated = False
                state.last_error = str(exc)
            except httpx.HTTPStatusError as exc:
                state.status = "error"
                state.last_error = f"HTTP {exc.response.status_code}: evaluator request failed."
                logger.exception("evaluator_request_failed harness=%s", harness)
            except Exception as exc:
                state.status = "error"
                state.authenticated = False
                state.last_error = f"{type(exc).__name__}: {exc}"[-4000:]
                logger.exception("evaluator_poll_failed")

            if active_tasks:
                completed, _ = await asyncio.wait(
                    active_tasks,
                    timeout=state.poll_seconds,
                    return_when=asyncio.FIRST_COMPLETED,
                )
                if completed:
                    await asyncio.gather(*completed, return_exceptions=True)
                    active_tasks.difference_update(completed)
                    state.active_run_count = len(active_tasks)
            else:
                await asyncio.sleep(state.poll_seconds)
    finally:
        for task in active_tasks:
            task.cancel()
        await asyncio.gather(*active_tasks, return_exceptions=True)


async def heartbeat_loop(
    settings: EvaluatorRuntimeSettings,
    instance_id: str,
    state: WorkerState,
    harness: Literal["codex", "muse", "opencode", "agy"],
) -> None:
    while True:
        try:
            await internal_request(
                settings,
                "POST",
                "/heartbeat",
                {
                    "instance_id": instance_id,
                    "harness": harness,
                    "status": state.status,
                    "harness_version": state.harness_version,
                    "authenticated": state.authenticated,
                    "active_run_count": state.active_run_count,
                    "last_error": state.last_error,
                },
            )
        except asyncio.CancelledError:
            raise
        except Exception:
            logger.exception("evaluator_heartbeat_failed")
        await asyncio.sleep(min(state.poll_seconds, 60))


